    print("Запуск доктестов...")
    print("=" * 60)
    
    # Запускаем доктесты для текущего модуля
    result = doctest.testmod(verbose=True)
    
    print("=" * 60)
    if result.failed == 0:
        print("✅ Все тесты пройдены успешно!")
    else:
        print(f"❌ Не пройдено тестов: {result.failed}")
    print("=" * 60)
    
    return result.failed


