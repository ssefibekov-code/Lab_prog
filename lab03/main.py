"""
Лабораторная работа №3 - Вариант 12
Расчётные задачи с использованием itertools и доктестов

Задачи:
1. Подсчёт 5-буквенных кодов из букв И,В,А,Н, где буква И используется хотя бы раз
2. Подсчёт количества значащих нулей в восьмеричной записи выражения
   7·512^120 − 6·64^100 + 8^210 − 255
3. Поиск числа с максимальным количеством делителей в диапазоне [84052; 84130]
"""

import itertools


# ============================================================
# Задача 1: Комбинаторика
# ============================================================

def task1() -> int:
    """
    Подсчитывает количество 5-буквенных кодов из букв И, В, А, Н,
    в которых буква И встречается хотя бы один раз.
    
    Алгоритм: перебираем все комбинации длиной 5 из 4 букв,
    считаем только те, где присутствует буква 'И'.
    
    Returns:
        int: количество кодов, удовлетворяющих условию
        
    Пример:
        >>> task1()
        781
    """
    letters = ['И', 'В', 'А', 'Н']
    code_length = 5
    total_codes_with_i = 0
    
    for combination in itertools.product(letters, repeat=code_length):
        if 'И' in combination:
            total_codes_with_i += 1
    
    return total_codes_with_i


# ============================================================
# Задача 2: Системы счисления
# ============================================================

def task2() -> int:
    """
    Вычисляет количество значащих нулей в восьмеричной записи выражения:
    7·512^120 − 6·64^100 + 8^210 − 255
    
    Returns:
        int: количество значащих нулей в восьмеричной записи
        
    Пример:
        >>> isinstance(task2(), int)
        True
    """
    term1 = 7 * (512 ** 120)
    term2 = 6 * (64 ** 100)
    term3 = 8 ** 210
    result = term1 - term2 + term3 - 255
    
    # Перевод в восьмеричную систему
    octal_string = oct(result)[2:]  # убираем префикс '0o'
    zero_count = octal_string.count('0')
    
    return zero_count


# ============================================================
# Задача 3: Делители числа
# ============================================================

def find_divisors_count(n: int) -> int:
    """
    Находит количество всех натуральных делителей числа n.
    
    Args:
        n (int): натуральное число
        
    Returns:
        int: количество делителей числа n
        
    Примеры:
        >>> find_divisors_count(1)
        1
        >>> find_divisors_count(12)
        6
        >>> find_divisors_count(48)
        10
        >>> find_divisors_count(84052)
        6
    """
    count = 0
    for i in range(1, int(n ** 0.5) + 1):
        if n % i == 0:
            count += 1
            if i != n // i:
                count += 1
    return count


def find_max_divisors_in_range(start: int, end: int) -> tuple:
    """
    Находит число в заданном диапазоне, имеющее максимальное количество делителей.
    Если таких чисел несколько, возвращает наименьшее.
    
    Args:
        start (int): начало диапазона (включительно)
        end (int): конец диапазона (включительно)
        
    Returns:
        tuple: (количество_делителей, число)
        
    Примеры:
        >>> find_max_divisors_in_range(2, 48)
        (10, 48)
        >>> find_max_divisors_in_range(84052, 84130)
        (72, 84084)
    """
    max_divisors = 0
    number_with_max = 0
    
    for num in range(start, end + 1):
        current_divisors = find_divisors_count(num)
        if current_divisors > max_divisors:
            max_divisors = current_divisors
            number_with_max = num
    
    return (max_divisors, number_with_max)


def task3() -> tuple:
    """
    Решает задачу 3 для диапазона [84052; 84130].
    Находит число с максимальным количеством делителей.
    
    Returns:
        tuple: (количество_делителей, число)
        
    Пример:
        >>> task3()
        (72, 84084)
    """
    start_num = 84052
    end_num = 84130
    return find_max_divisors_in_range(start_num, end_num)


# ============================================================
# Дополнительная функция для анализа диапазона
# ============================================================

def analyze_range(start: int, end: int) -> None:
    """
    Анализирует диапазон чисел и выводит информацию о делителях.
    
    Args:
        start (int): начало диапазона
        end (int): конец диапазона
    """
    print(f"\nАнализ диапазона [{start}; {end}]:")
    print("=" * 60)
    
    for num in range(start, end + 1):
        divisors_count = find_divisors_count(num)
        if divisors_count > 30:  # Выводим числа с большим количеством делителей
            print(f"  {num}: {divisors_count} делителей")
    
    print("=" * 60)


